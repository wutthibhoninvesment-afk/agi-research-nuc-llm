"""swe.killerrepin — the differential re-pin of a GENERATED oracle file.

Round 450 (language C). `languages/whence/tests/test_generated_killers.py`
says "do not edit by hand" and cannot be regenerated (the mutation JSONs its
killers came from are not kept), so when a deliberate language change moves
one of its expectations the only supported moves are "hand-edit the file that
says not to" or "delete the test". Both silently destroy the discrimination
the test exists for, and nothing in the repo would say so.

These tests cover the two properties that make the re-pin safe:

  * a pin is rewritten ONLY when the baseline tree reproduces its OLD
    expectation exactly, so the movement is attributable to the working-tree
    diff and to nothing else; and
  * the rewrite is byte-identical to what `killers.render_tests` would have
    generated, so a re-pinned file is a generated file.
"""
import os
import subprocess
import sys
import textwrap

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import pytest

from swe import killerrepin, killers

FIXTURE = textwrap.dedent('''\
    """GENERATED by harness/swe/killers.py — do not edit by hand."""


    def test_kill_values_py_139_const_121():
        """mutant values.py:139:const#121: 12 -> 13 (line 139) — mutant gave {'kind': 'ok'}"""
        src = 'let v1 = [nosuch(1)]\\n'
        assert run(src) == {'kind': 'ok', 'vals': {'v1': '[miss]'}}


    def test_kill_interp_py_486_ifneg_150():
        """mutant interp.py:486:ifneg#150: negate if-condition (line 486) — mutant gave {'kind': 'crash'}"""
        src = 'print(1)\\n'
        assert run(src) == {'kind': 'ok', 'out': ['1']}
    ''')


def test_parse_pins_reads_the_generated_shape():
    pins = killerrepin.parse_pins(FIXTURE)
    assert [p.name for p in pins] == ["test_kill_values_py_139_const_121",
                                      "test_kill_interp_py_486_ifneg_150"]
    a, b = pins
    assert (a.path, a.lineno, a.desc) == ("values.py", 139, "12 -> 13")
    assert a.src == "let v1 = [nosuch(1)]\n"
    assert a.expected == {"kind": "ok", "vals": {"v1": "[miss]"}}
    assert (b.path, b.lineno, b.desc) == ("interp.py", 486, "negate if-condition")


def test_parse_pins_skips_anything_that_is_not_a_generated_killer():
    text = FIXTURE + textwrap.dedent('''

        def test_written_by_a_human():
            """not a mutant docstring"""
            assert 1 == 1


        def test_kill_no_assert():
            """mutant values.py:1:const#0: 1 -> 2 (line 1) — mutant gave {}"""
            src = 'x\\n'
        ''')
    assert len(killerrepin.parse_pins(text)) == 2


def test_rewrite_is_byte_identical_to_what_render_tests_would_emit():
    """A re-pinned file must still be a GENERATED file, or the next real
    regeneration produces a spurious diff."""
    pins = killerrepin.parse_pins(FIXTURE)
    new = {"kind": "ok", "vals": {"v1": '[miss "unbound name \'nosuch\'"]'}}
    out = killerrepin.rewrite(FIXTURE, [(pins[0], new)])
    assert "    assert run(src) == %r\n" % (new,) in out
    assert killerrepin.parse_pins(out)[0].expected == new
    # the untouched pin is untouched, to the byte
    assert killerrepin.parse_pins(out)[1].expected == pins[1].expected
    assert out.count("def test_kill_") == 2


def test_rewrite_applies_bottom_up_so_line_numbers_cannot_drift():
    """Both pins at once, with a replacement whose repr is much longer than
    the line it replaces. Applied top-down the second pin's recorded line
    range would already be stale."""
    pins = killerrepin.parse_pins(FIXTURE)
    long_ = {"kind": "ok", "vals": {"v1": "x" * 400}}
    out = killerrepin.rewrite(FIXTURE, [(pins[0], long_), (pins[1], long_)])
    got = killerrepin.parse_pins(out)
    assert [p.expected for p in got] == [long_, long_]


def test_moved_keys_names_the_leaf_that_moved():
    old = {"kind": "ok", "out": ["a"], "vals": {"v1": "1", "v2": "2"}}
    new = {"kind": "ok", "out": ["a"], "vals": {"v1": "9", "v2": "2"}}
    assert killerrepin.moved_keys(old, new) == ["vals.v1"]
    assert killerrepin.moved_keys(old, old) == []
    assert killerrepin.moved_keys(
        old, {"kind": "ok", "out": ["b"], "vals": old["vals"]}) == ["out[0]"]


def test_moved_keys_handles_a_length_change_without_pretending_to_align():
    assert killerrepin.moved_keys({"out": ["a"]}, {"out": ["a", "b"]}) == ["out"]


