def _have_git_whence():
    if not os.path.isdir(os.path.join(killerrepin.WHENCE_ROOT, "whence")):
        return False
    r = subprocess.run(["git", "rev-parse", "--is-inside-work-tree"],
                       cwd=killerrepin.WHENCE_ROOT, capture_output=True)
    return r.returncode == 0


needs_tree = pytest.mark.skipif(not _have_git_whence(),
                                reason="no git checkout of languages/whence")


@needs_tree
def test_every_live_pin_holds_against_the_committed_tree():
    """The green-tree statement, and the one that makes `--write` meaningful:
    with the working tree and HEAD agreeing, EVERY pin must be `holds`. A
    `stale` here would mean the generated file is out of step with the
    interpreter for a reason nobody declared."""
    pins = killerrepin.parse_pins(
        open(killerrepin.TEST_PATH, encoding="utf-8").read())
    assert len(pins) > 40, "the generated file lost its pins"
    results = killerrepin.judge_all(pins, ref="HEAD")
    bad = [(p.name, v) for p, v, _, _ in results if v != "holds"]
    assert bad == [], bad


@needs_tree
def test_a_pin_the_baseline_cannot_reproduce_is_stale_and_is_not_written():
    """The refusal. A pin whose expectation neither tree produces is not a
    re-pin candidate — rewriting it would paste in today's output and call
    the result a regression pin."""
    pins = killerrepin.parse_pins(
        open(killerrepin.TEST_PATH, encoding="utf-8").read())[:1]
    pins[0].expected = {"kind": "ok", "out": ["nothing produces this"]}
    results = killerrepin.judge_all(pins, ref="HEAD")
    assert [v for _, v, _, _ in results] == ["stale"]


@needs_tree
def test_the_mutant_ids_in_the_generated_file_have_decayed():
    """Round 450's measurement, kept as an instrument rather than a sentence.

    The obvious way to verify a re-pin is "rebuild the mutant from its id and
    check the test still separates it". A mutant id is a LINE NUMBER plus a
    generation counter, both of which move whenever the mutated file is
    edited — and at round 450 NOT ONE of the pins resolved. This asserts the
    weak, durable half (the census runs and the ids are decayed rather than
    silently half-working); the exact number belongs in the round file, not
    in an assertion that a lucky edit could flip."""
    pins = killerrepin.parse_pins(
        open(killerrepin.TEST_PATH, encoding="utf-8").read())
    scores = killerrepin.audit_ids(pins)
    assert set(scores) == {p.name for p in pins}
    exact = [n for n, (e, _) in scores.items() if e == 1]
    assert len(exact) < len(pins) // 2, (
        "mutant ids resolve again (%d of %d) — if a campaign has re-pinned "
        "them, killerrepin can verify by rebuild and this test should say so"
        % (len(exact), len(pins)))
