# ------------------------------------------------- subject scope (round 361) --
#
# The subject half of the freshness gate. `checkout_digest` is one sha over
# the whole whence checkout, and 52% of the commits that move it touch
# nothing any slow-tier file imports. These tests pin the narrowing AND — the
# part that matters — every way it is refused.

import swe.readscope as RS


def _scoped_entry(dirs, digs, **kw):
    e = _entry(checkout_digest="OLD")
    e["subject_scope"] = {"ok": True, "dirs": list(dirs), "opaque": [],
                          "n_reads": len(dirs), "why": ""}
    e["subject_digests"] = dict(digs)
    e["schema"] = 3
    e.update(kw)
    return e


def test_a_pyc_read_is_evidence_about_its_source_not_about_pycache():
    """With a populated `__pycache__`, importing `whence.parser` opens the
    `.pyc` and never opens the `.py`. Recording the raw path would place the
    scope in a directory the digest ignores by construction."""
    assert RS.normalize_read("whence/__pycache__/parser.cpython-312.pyc") \
        == "whence/parser.py"
    assert RS.normalize_read("whence/parser.py") == "whence/parser.py"
    assert RS.normalize_read(".git/objects/ab/cdef") is None
    # a pyc whose SOURCE would still be ignored is not resurrected
    assert RS.normalize_read(".venv/__pycache__/x.cpython-312.pyc") is None


def test_scope_is_directories_not_files():
    """Rule 2. `list_example_files` shells `git ls-files`, so a NEW example
    changes what the corpus contains without any existing file being opened.
    A file-granular scope would be fail-open against exactly that."""
    assert RS.scope_dirs(["examples/self_eval.lang", "whence/parser.py"]) \
        == ["examples", "whence"]
    assert RS.scope_dirs(["run.py"]) == ["."]
    assert RS.scope_dirs([]) == []


def test_dir_digest_notices_an_added_file_of_any_extension(tmp_path):
    root = tmp_path / "co"
    (root / "examples").mkdir(parents=True)
    (root / "examples" / "self_eval.lang").write_text("guest = 1\n")
    d = RS.dir_digest(str(root), "examples")
    (root / "examples" / "new_case.lang").write_text("x\n")
    assert RS.dir_digest(str(root), "examples") != d
    assert RS.dir_digest(str(tmp_path), "nope") == "<missing>"


def test_dir_digest_is_not_recursive():
    """`scope_dirs` reports every directory actually read, so a subdirectory
    that matters appears on its own. Recursing would silently re-couple
    `whence/` to trees nothing in it reads."""
    import tempfile
    d = tempfile.mkdtemp()
    os.makedirs(os.path.join(d, "a", "b"))
    open(os.path.join(d, "a", "x.py"), "w").write("1")
    before = RS.dir_digest(d, "a")
    open(os.path.join(d, "a", "b", "y.py"), "w").write("1")
    assert RS.dir_digest(d, "a") == before


def test_a_checkout_move_outside_the_scope_is_scoped_not_stale():
    """Rule 7. The claim is weaker, so it gets its OWN state and its own
    counter — it is never folded into `CONCLUSIVE`."""
    e = _scoped_entry(["whence"], {"whence": "W1"})
    assert ST.classify(e, "NEW", {"swe/fuzz.py": "aaa"}, {"whence": "W1"}) \
        == "fresh_pass_scoped"
    assert "fresh_pass_scoped" not in ST.CONCLUSIVE
    assert "fresh_pass_scoped" in ST.SCOPED_CONCLUSIVE


def test_a_checkout_move_inside_the_scope_is_stale_subject():
    """Rule 8, and it names the directory rather than counting one."""
    e = _scoped_entry(["whence", "examples"],
                      {"whence": "W1", "examples": "E1"})
    cur = {"whence": "W1", "examples": "E2"}
    assert ST.classify(e, "NEW", {"swe/fuzz.py": "aaa"}, cur) == "stale_subject"
    assert "stale_subject" not in ST.CONCLUSIVE
    assert "stale_subject" not in ST.SCOPED_CONCLUSIVE
    assert ST.moved_scope(e, cur) == ["examples"]


def test_a_scoped_failure_is_still_counted_as_failing():
    """A weaker freshness claim does not make the red less red."""
    e = _scoped_entry(["whence"], {"whence": "W1"}, outcome="failed")
    assert ST.classify(e, "NEW", {"swe/fuzz.py": "aaa"}, {"whence": "W1"}) \
        == "fresh_fail_scoped"
    assert "fresh_fail_scoped" in ST.FAILING and "fresh_fail" in ST.FAILING


def test_an_opaque_run_can_never_narrow_anything():
    """Rule 9, half one. `swe/coverage.py` spawns a pytest over the real
    checkout; that child has no audit hook, so its reads are invisible and
    nothing may be narrowed on their account."""
    scope = {"ok": True, "dirs": ["whence"], "opaque": ["subprocess.Popen"],
             "n_reads": 3, "why": ""}
    assert not RS.scope_is_narrowable(scope)
    e = _scoped_entry(["whence"], {"whence": "W1"})
    e["subject_scope"] = scope
    assert ST.scope_digests_now(e) is None
    assert ST.classify(e, "NEW", {"swe/fuzz.py": "aaa"},
                       ST.scope_digests_now(e)) == "stale_checkout"


def test_a_missing_or_torn_scope_record_falls_back_to_rule_2(tmp_path):
    """Rule 9, half two: no observation is not a narrow observation."""
    missing = RS.read_scope_file(str(tmp_path / "absent.json"))
    assert missing["ok"] is False and missing["why"] == "missing"
    torn = tmp_path / "torn.json"
