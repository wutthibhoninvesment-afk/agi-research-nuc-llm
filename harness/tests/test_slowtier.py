def _status_over(tmp_path, entries, files, digest="D"):
    tests = tmp_path / "t"
    tests.mkdir(exist_ok=True)
    for f in files:
        (tests / f).write_text("")
    p = str(tmp_path / "l.jsonl")
    for e in entries:
        # Round 343: these entries are about SUBJECT staleness, so stamp them
        # with the harness digest they would really have been written with.
        # Without it every one classifies `unstamped` and the tests below stop
        # testing what they were written to test — a schema change silently
        # neutering the suite that guards it.
        e.setdefault("dep_digests",
                     ST.dep_digests(e["file"], tests_dir=str(tests)))
        ST.append_entry(p, e)
    return ST.status(ledger_path=p, tests_dir=str(tests), digest=digest)


def test_status_reports_its_own_recall(tmp_path):
    """Round 339's rule: a checker nobody is watching must report the size
    of its own blind spot, or a partial sweep reads as a complete one."""
    st = _status_over(tmp_path, [
        {"file": "test_swe_a.py", "outcome": "passed", "finished_at": 5,
         "checkout_digest": "D", "checkout_stable": True},
        {"file": "test_swe_b.py", "outcome": "passed", "finished_at": 5,
         "checkout_digest": "OLD", "checkout_stable": True},
    ], ["test_swe_a.py", "test_swe_b.py", "test_swe_c.py"])
    assert st["n_files"] == 3 and st["n_conclusive"] == 1
    assert abs(st["coverage"] - 1.0 / 3) < 1e-9
    by = dict((r["file"], r["state"]) for r in st["rows"])
    assert by == {"test_swe_a.py": "fresh_pass",
                  "test_swe_b.py": "stale_checkout",
                  "test_swe_c.py": "unknown"}


