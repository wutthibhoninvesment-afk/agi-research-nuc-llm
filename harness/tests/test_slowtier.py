def test_digest_is_stable_and_content_sensitive(tmp_path):
    root = tmp_path / "co"
    (root / "whence").mkdir(parents=True)
    (root / "whence" / "interp.py").write_text("x = 1\n")
    (root / "whence" / "parser.py").write_text("y = 2\n")
    d1 = ST.checkout_digest(str(root))
    assert d1 == ST.checkout_digest(str(root))          # stable
    (root / "whence" / "interp.py").write_text("x = 2\n")
    assert ST.checkout_digest(str(root)) != d1          # content-sensitive


def test_digest_ignores_bytecode_caches_and_documentation(tmp_path):
    """A digest that moved every time the suite RAN would mark every result
    stale immediately — self-defeating. `__pycache__`/`.pytest_cache` are
    regenerated by merely running the tests, and a SPEC.md edit cannot
    move a line number in a `.py` source.

    Round 361 renamed this from `..._and_non_python`: the digest now covers
    `.lang` too (`_SOURCE_EXTS`), so the excluded set is documentation and
    caches, not "everything that is not Python". Nothing this test asserts
    changed."""
    root = tmp_path / "co"
    (root / "whence").mkdir(parents=True)
    (root / "whence" / "interp.py").write_text("x = 1\n")
    d = ST.checkout_digest(str(root))
    (root / "whence" / "__pycache__").mkdir()
    (root / "whence" / "__pycache__" / "interp.cpython-311.pyc").write_bytes(b"\x00bytecode")
    (root / ".pytest_cache").mkdir()
    (root / ".pytest_cache" / "junk.py").write_text("noise = 1\n")
    (root / "SPEC.md").write_text("# a doc edit\n")
    (root / ".venv").mkdir()
    (root / ".venv" / "lib.py").write_text("vendored = 1\n")
    assert ST.checkout_digest(str(root)) == d


def test_digest_notices_a_renamed_file(tmp_path):
    """Path names are folded in, not just contents — moving a module is a
    change that shifts what a scratch copy contains."""
    root = tmp_path / "co"
    root.mkdir()
    (root / "a.py").write_text("v = 1\n")
    d = ST.checkout_digest(str(root))
    os.rename(str(root / "a.py"), str(root / "b.py"))
    assert ST.checkout_digest(str(root)) != d


