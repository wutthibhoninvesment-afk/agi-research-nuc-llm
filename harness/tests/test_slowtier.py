def _fast_script():
    return os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "run_tests_fast.sh")


def test_fast_health_check_still_returns_pytests_own_exit_code():
    """Round 341 changed `run_tests_fast.sh` from `exec pytest` to
    run-then-report, which is exactly the shape that silently swallows an
    exit code. Both paths are exercised for real (collection only, so this
    stays a fast-tier test): a matching `-k` exits 0, a non-matching one
    exits pytest's own 5 (`NO_TESTS_COLLECTED`).

    Also asserts the slow-tier report is actually PRINTED — a diagnostic
    nobody sees is the failure mode this whole module exists to fix."""
    import subprocess
    ok = subprocess.run(["bash", _fast_script(), "--collect-only", "-q",
                         "-k", "test_digest_is_stable_and_content_sensitive"],
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    assert ok.returncode == 0, ok.stdout[-2000:]
    assert b"slow tier:" in ok.stdout, ok.stdout[-2000:]

    none = subprocess.run(["bash", _fast_script(), "--collect-only", "-q",
                           "-k", "zzz_no_such_test_name_zzz"],
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    assert none.returncode == 5, (none.returncode, none.stdout[-2000:])
    assert b"slow tier:" in none.stdout, none.stdout[-2000:]


