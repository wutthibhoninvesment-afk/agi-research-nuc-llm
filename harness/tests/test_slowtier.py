def test_no_entry_is_unknown_never_pass():
    """Rule 1. The whole point: a tier nobody ran must not read as green,
    which is exactly how round 338's five failures stayed invisible."""
    assert ST.classify(None, "abc") == "unknown"


def test_a_pass_against_a_different_checkout_is_stale_not_fresh():
    """Rule 2."""
    e = {"outcome": "passed", "checkout_digest": "old", "checkout_stable": True}
    assert ST.classify(e, "new") == "stale_checkout"
    assert ST.classify(e, "old") == "fresh_pass"


def test_a_result_computed_while_the_checkout_moved_is_never_evidence():
    """Rule 3, and round 341's own finding made mechanical: a PASS produced
    while another round was editing `languages/whence/` is no more
    trustworthy than the FAIL it might equally have produced."""
    for outcome in ("passed", "failed"):
        e = {"outcome": outcome, "checkout_digest": "same", "checkout_stable": False}
        assert ST.classify(e, "same") == "raced"
    assert "raced" not in ST.CONCLUSIVE


def test_an_unrecognised_outcome_falls_back_to_unknown():
    """Fail-closed on the default branch too — a `timeout` outcome is not
    a pass and must not be counted as one."""
    e = {"outcome": "timeout", "checkout_digest": "d", "checkout_stable": True}
    assert ST.classify(e, "d") == "unknown"


