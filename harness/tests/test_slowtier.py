"""Tests for `harness/swe/slowtier.py` — the recorded, resumable slow-tier
ledger (round 341, SWE-loop D).

Deliberately NOT named `test_swe_*.py`: `harness/tests/conftest.py` marks
every file with that prefix `swe_slow`, and a module whose whole purpose is
to make the slow tier visible to the FAST health check must itself run in
the fast tier. Every test here injects a fake runner and a fake clock —
nothing shells out to pytest, nothing reads the real whence checkout except
the two tests that say so in their names.
"""
