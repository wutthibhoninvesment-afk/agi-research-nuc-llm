    assert st["n_conclusive"] == 1 and st["n_scoped"] == 1
    assert st["coverage"] == 0.5 and st["coverage_scoped"] == 1.0
    txt = ST.report_text(st)
    assert "1 conclusive" in txt
    assert "conclusive WITHIN their measured read-scope only" in txt


