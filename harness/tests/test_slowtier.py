def test_run_slice_records_the_scope_and_a_scopeless_runner_is_fail_closed(tmp_path):
    root = tmp_path / "co"
    (root / "whence").mkdir(parents=True)
    (root / "whence" / "interp.py").write_text("x = 1\n")
    (root / "examples").mkdir()
    (root / "examples" / "self_eval.lang").write_text("guest = 1\n")
    tests = tmp_path / "t"
    tests.mkdir()
    (tests / "test_swe_a.py").write_text("")
    (tests / "test_swe_b.py").write_text("")
    led = str(tmp_path / "l.jsonl")

    def runner(f):
        if f == "test_swe_a.py":
            return {"returncode": 0, "timed_out": False, "tail": "",
                    "scope": {"ok": True, "dirs": ["whence"], "opaque": [],
                              "n_reads": 1, "why": ""}}
        return {"returncode": 0, "timed_out": False, "tail": ""}   # no scope

    a, b = ST.run_slice(["test_swe_a.py", "test_swe_b.py"], ledger_path=led,
                        whence_root=str(root), runner=runner,
                        clock=lambda: 1.0, tests_dir=str(tests))
    assert a["schema"] == 3
    assert a["subject_digests"] == {"whence": RS.dir_digest(str(root), "whence")}
    # A runner that reports nothing is not a runner that reported "nothing".
    assert b["subject_digests"] is None
    assert b["subject_scope"]["why"] == "runner-gave-none"
    assert ST.classify(b, "NEW", b["dep_digests"], ST.scope_digests_now(b)) \
        == "stale_checkout"
    # ... and the one that DID report is unaffected by an edit outside it.
    (root / "examples" / "self_eval.lang").write_text("guest = 2\n")
    assert ST.classify(a, ST.checkout_digest(str(root)), a["dep_digests"],
                       ST.scope_digests_now(a, str(root))) == "fresh_pass_scoped"
    # ... and IS affected by one inside it.
    (root / "whence" / "interp.py").write_text("x = 2\n")
    assert ST.classify(a, ST.checkout_digest(str(root)), a["dep_digests"],
                       ST.scope_digests_now(a, str(root))) == "stale_subject"


def test_status_reports_the_two_recalls_separately(tmp_path):
    """Round 334's rule, applied here: three rounds of reported figures and
    `run_tests_fast.sh`'s printed line depend on what `n_conclusive` has
    meant since round 341, so the weaker number is a NEW field."""
    tests = tmp_path / "t"
    tests.mkdir()
    for f in ("test_swe_a.py", "test_swe_b.py"):
        (tests / f).write_text("")
    p = str(tmp_path / "l.jsonl")
    fresh = _entry(file="test_swe_a.py", checkout_digest="D")
    fresh["dep_digests"] = ST.dep_digests("test_swe_a.py", tests_dir=str(tests))
    scoped = _scoped_entry([], {}, file="test_swe_b.py")
    scoped["dep_digests"] = ST.dep_digests("test_swe_b.py", tests_dir=str(tests))
