def test_slow_tier_files_matches_conftests_own_rule():
    """`conftest.pytest_collection_modifyitems` marks exactly
    `basename.startswith("test_swe_")`. If that rule ever changes, this
    module's whole notion of 'the tier' silently drifts from pytest's."""
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "conftest.py"), encoding="utf-8").read()
    assert 'startswith("test_swe_")' in src
    files = ST.slow_tier_files()
    assert files and all(f.startswith("test_swe_") and f.endswith(".py") for f in files)
    assert "test_slowtier.py" not in files          # this file is fast-tier


def test_latest_by_file_takes_the_newest_entry(tmp_path):
    p = str(tmp_path / "l.jsonl")
    ST.append_entry(p, {"file": "test_swe_a.py", "outcome": "failed", "finished_at": 10})
    ST.append_entry(p, {"file": "test_swe_a.py", "outcome": "passed", "finished_at": 20})
    ST.append_entry(p, {"file": "test_swe_b.py", "outcome": "failed", "finished_at": 15})
    best = ST.latest_by_file(ST.read_entries(p))
    assert best["test_swe_a.py"]["outcome"] == "passed"
    assert best["test_swe_b.py"]["outcome"] == "failed"


def test_a_torn_last_line_is_skipped_not_fatal(tmp_path):
    """A round killed mid-append (round 338/339 both died at max-turns)
    leaves a partial line. Absence of a record is handled by rule 1; a
    crash here would take the whole health check down with it."""
    p = str(tmp_path / "l.jsonl")
    ST.append_entry(p, {"file": "test_swe_a.py", "outcome": "passed", "finished_at": 1})
    with open(p, "a") as f:
        f.write('{"file": "test_swe_b.py", "outc')
    entries = ST.read_entries(p)
    assert len(entries) == 1 and entries[0]["file"] == "test_swe_a.py"


def test_read_entries_on_a_missing_ledger_is_empty_not_an_error(tmp_path):
    assert ST.read_entries(str(tmp_path / "nope.jsonl")) == []


