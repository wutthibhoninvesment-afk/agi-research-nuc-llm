def test_run_slice_records_one_entry_per_file_with_a_fake_runner(tmp_path):
    p = str(tmp_path / "l.jsonl")
    root = tmp_path / "co"
    (root).mkdir()
    (root / "a.py").write_text("v = 1\n")
    seen = []

    def runner(f):
        seen.append(f)
        return {"returncode": 0 if f.endswith("a.py") else 1,
                "timed_out": False, "tail": "output for " + f}

    ticks = iter([100.0, 130.0, 200.0, 260.0])
    written = ST.run_slice(["test_swe_a.py", "test_swe_b.py"], ledger_path=p,
                           whence_root=str(root), runner=runner,
                           clock=lambda: next(ticks))
    assert seen == ["test_swe_a.py", "test_swe_b.py"]
    assert [e["outcome"] for e in written] == ["passed", "failed"]
    assert [e["seconds"] for e in written] == [30.0, 60.0]
    assert all(e["checkout_stable"] for e in written)
    on_disk = ST.read_entries(p)
    assert len(on_disk) == 2 and on_disk[0]["file"] == "test_swe_a.py"


def test_run_slice_flags_a_checkout_that_moves_mid_run(tmp_path):
    """The mechanism behind four of round 338's five failures, caught and
    recorded instead of silently believed. The runner here edits the tree
    while it 'runs', exactly as a concurrent language(C) round does."""
    p = str(tmp_path / "l.jsonl")
    root = tmp_path / "co"
    root.mkdir()
    (root / "interp.py").write_text("v = 1\n")

    def runner(f):
        (root / "interp.py").write_text("# a concurrent round landed here\nv = 1\n")
        return {"returncode": 0, "timed_out": False, "tail": ""}

    written = ST.run_slice(["test_swe_a.py"], ledger_path=p, whence_root=str(root),
                           runner=runner, clock=iter([1.0, 2.0]).__next__)
    e = written[0]
    assert e["outcome"] == "passed"                       # pytest was happy
    assert e["checkout_stable"] is False                  # ...and it does not count
    assert e["checkout_digest"] != e["checkout_digest_after"]
    assert ST.classify(e, e["checkout_digest"]) == "raced"


